package com.ultiweb.jobs.svc.ai;

import static org.assertj.core.api.Assertions.assertThat;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import com.ultiweb.jobs.EmailManagementAgent;
import com.ultiweb.jobs.svc.email.EmailMessage;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.Test;
import org.springframework.boot.test.context.ConfigDataApplicationContextInitializer;
import org.springframework.boot.test.context.runner.ApplicationContextRunner;
import tools.jackson.databind.ObjectMapper;

class LmStudioSummaryIntegrationTest {
	@Test
	void sendsSummariesToLmStudioAndClassificationToDeepInfra() throws IOException {
		// given
		final AtomicReference<String> lmStudioBody = new AtomicReference<>();
		final AtomicReference<String> deepInfraBody = new AtomicReference<>();
		final HttpServer server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
		server.createContext("/lm/v1/chat/completions", exchange -> {
			lmStudioBody.set(new String(exchange.getRequestBody().readAllBytes(), StandardCharsets.UTF_8));
			respond(exchange, "Summary generated by Qwen in LM Studio.");
		});
		server.createContext("/deep/v1/openai/chat/completions", exchange -> {
			deepInfraBody.set(new String(exchange.getRequestBody().readAllBytes(), StandardCharsets.UTF_8));
			respond(exchange, "Dev_Jobs");
		});
		server.start();
		try {
			final String baseUrl = "http://127.0.0.1:" + server.getAddress().getPort();
			new ApplicationContextRunner()
					.withInitializer(context -> {
						context.getEnvironment().getPropertySources().remove("systemEnvironment");
						context.getEnvironment().getPropertySources().remove("systemProperties");
						new ConfigDataApplicationContextInitializer().initialize(context);
					})
					.withUserConfiguration(EmailManagementAgent.class)
					.withPropertyValues("spring.profiles.active=test,ollama,deepinfra,lmstudio",
							"GMAIL_CLIENT_ID=test-client", "GMAIL_CLIENT_SECRET=test-secret",
							"DEEPINFRA_API_KEY=test-deepinfra-key", "DEEPINFRA_BASE_URL=" + baseUrl + "/deep/v1/openai",
							"LMSTUDIO_API_KEY=lm-studio", "LMSTUDIO_BASE_URL=" + baseUrl + "/lm/v1",
							"LMSTUDIO_MODEL=qwen-local")
					.run(context -> {
						assertThat(context).hasNotFailed();
						final var email = new EmailMessage("account", "id", "Subject", "sender@example.com", "Email body.");

						// when
						final String summary = context.getBean(EmailSummarySvc.class).summarize(email);
						final EmailTag tag = context.getBean(EmailTagSvc.class).suggestTag(summary).orElseThrow();

						// then
						assertThat(summary).isEqualTo("Summary generated by Qwen in LM Studio.");
						assertThat(tag).isEqualTo(EmailTag.DEV_JOBS);
						final ObjectMapper mapper = new ObjectMapper();
						assertThat(mapper.readTree(lmStudioBody.get()).get("model").asString()).isEqualTo("qwen-local");
						assertThat(mapper.readTree(deepInfraBody.get()).get("model").asString())
								.isEqualTo("meta-llama/Meta-Llama-3.1-8B-Instruct-Turbo");
					});
		} finally {
			server.stop(0);
		}
	}

	private static void respond(final HttpExchange exchange, final String content) throws IOException {
		final String json = """
				{"id":"test-completion","object":"chat.completion","created":1,"model":"test/model",
				"choices":[{"index":0,"message":{"role":"assistant","content":"%s"},"finish_reason":"stop"}],
				"usage":{"prompt_tokens":10,"completion_tokens":4,"total_tokens":14}}
				""".formatted(content);
		final byte[] response = json.getBytes(StandardCharsets.UTF_8);
		exchange.getResponseHeaders().set("Content-Type", "application/json");
		exchange.sendResponseHeaders(200, response.length);
		try (final var body = exchange.getResponseBody()) {
			body.write(response);
		}
	}
}
